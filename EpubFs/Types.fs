namespace EpubFs

open Giraffe.ViewEngine
open System
open System.IO

/// See: https://www.w3.org/TR/epub-33/#sec-smil-par-elem
type ParNode = {
    /// The fragment identifier (e.g., "#line1") referencing an element in the content file. The content file name is automatically prepended when writing the SMIL.
    TextFragmentReference: string
    ClipBegin: Choice<string, TimeSpan>
    ClipEnd: Choice<string, TimeSpan> }

type SmilInput =
    /// A raw SMIL file provided as a stream. Use this when you have a pre-built SMIL file.
    | Raw of Stream
    /// A list of XML nodes representing the head and body content of the SMIL file.
    | Structured of head: XmlNode seq * body: XmlNode seq
    /// A simplified representation using ParNode records. Each ParNode generates a `<par>` element with text and audio synchronization.
    | ParNodes of audioFileReference: string * parNodes: ParNode seq

type ContentInput =
    /// A raw XHTML file provided as a stream. Use this when you have a pre-built XHTML file.
    | Raw of Stream
    /// A list of XML nodes representing the body content. The XHTML document structure (html, head, body) will be generated automatically.
    | Structured of body: XmlNode seq

/// Text used in the autogenerated navigation document.
type NavLabels = {
    /// Heading of the table of contents, and its entry in the landmarks.
    TableOfContents: string
    /// Heading of the (hidden) landmarks list.
    Landmarks: string
    /// Landmarks entry pointing to the first content file with Navigation set (`bodymatter`).
    StartOfContent: string }
with
    static member English = { TableOfContents = "Table of Contents"; Landmarks = "Landmarks"; StartOfContent = "Start of Content" }

type NavInput =
    /// Automatically generate the navigation document (table of contents and landmarks) from the title page and ContentFiles
    /// that have Navigation or Landmark set, using the given labels (e.g. `NavLabels.English`).
    | Autogenerated of NavLabels
    /// A raw navigation XHTML file provided as a stream. Use this when you need custom navigation structure.
    | Raw of Stream

/// See: https://www.w3.org/TR/epub-33/#attrdef-spine-page-progression-direction
type PageProgressionDirection =
    /// Left to right.
    | Ltr
    /// Right to left, e.g. for Arabic, Hebrew, or vertical Japanese.
    | Rtl

type CoverImage = {
    Input: Stream
    /// Media type of the image, such as "image/jpeg".
    MediaType: string
    /// File extension including the dot, such as ".jpg".
    Extension: string }

/// Media overlay metadata properties.
/// See: https://www.w3.org/TR/epub-33/#app-overlays-vocab
type MediaOverlayMetadata = {
    /// Total duration of the entire publication.
    TotalDuration: Choice<string, TimeSpan>
    /// CSS class for the currently playing element.
    ActiveClass: string option
    /// CSS class added to the root element during playback.
    PlaybackActiveClass: string option
    /// Name(s) of the narrator(s), optional.
    Narrators: string seq }

/// A vocabulary prefix declared in the package document's `prefix` attribute.
/// The `media` prefix (media overlays) is always declared; reserved prefixes such as `dcterms` and `rendition` need no declaration.
/// See: https://www.w3.org/TR/epub-33/#sec-prefix-attr
type Prefix = {
    /// The prefix name without the colon, such as "ibooks".
    Name: string
    /// The vocabulary IRI the prefix maps to, such as "http://vocabulary.itunes.apple.com/rdf/ibooks/vocabulary-extensions-1.0/".
    Iri: string }

/// An additional `<meta>` element in the package metadata, such as `ibooks:specified-fonts` or `rendition:flow`.
/// See: https://www.w3.org/TR/epub-33/#sec-meta-elem
type MetaProperty = {
    /// The property, normally prefixed, such as "ibooks:specified-fonts". Declare non-reserved prefixes in `Metadata.Prefixes`.
    Property: string
    Value: string
    /// Optional `refines` target, such as "#creator1".
    Refines: string option }

type Metadata = {
    /// See: https://www.w3.org/TR/epub-33/#sec-opf-dcidentifier
    Id: string 
    /// See: https://www.w3.org/TR/epub-33/#sec-opf-dctitle
    Title: string
    /// At least one required, with the first one considered primary.
    /// See: https://www.w3.org/TR/epub-33/#sec-opf-dclanguage
    Languages: string seq
    /// `None` defaults to DateTimeOffset.UtcNow
    /// See: https://www.w3.org/TR/epub-33/#last-modified-date
    ModifiedAt: DateTimeOffset option
    /// Optional.
    /// See: https://www.w3.org/TR/epub-33/#sec-opf-dccreator
    Creators: string seq
    /// See: https://www.w3.org/TR/epub-33/#sec-opf-dcmes-optional-def
    Source: string option
    /// Book summary or blurb.
    /// See: https://www.w3.org/TR/epub-33/#sec-opf-dcmes-optional-def
    Description: string option
    /// Publisher name.
    /// See: https://www.w3.org/TR/epub-33/#sec-opf-dcmes-optional-def
    Publisher: string option
    /// Categories or tags for the publication. Optional.
    /// See: https://www.w3.org/TR/epub-33/#sec-opf-dcmes-optional-def
    Subjects: string seq
    /// Copyright or rights statement. Optional.
    /// See: https://www.w3.org/TR/epub-33/#sec-opf-dcmes-optional-def
    Rights: string option
    /// Media overlay metadata. Required when the publication contains media overlays.
    /// See: https://www.w3.org/TR/epub-33/#sec-media-overlays
    MediaOverlay: MediaOverlayMetadata option
    /// Additional vocabulary prefixes for properties used in `Meta`.
    /// See: https://www.w3.org/TR/epub-33/#sec-prefix-attr
    Prefixes: Prefix seq
    /// Additional `<meta>` elements, written after all the others.
    /// See: https://www.w3.org/TR/epub-33/#sec-meta-elem
    Meta: MetaProperty seq }

type CssFile = {
    FileName: string
    Input: Stream }

type OtherFile = {
    FileName: string
    MediaType: string
    Compress: bool
    Input: Stream }

type SmilFile = {
    Input: SmilInput
    /// Duration of this media overlay. Used for media:duration metadata with refines.
    Duration: Choice<string, TimeSpan> }

/// https://www.w3.org/TR/epub-33/#attrdef-itemref-linear
type Navigation =
    /// Content that contributes to the primary reading order and has to be read sequentially.
    | Linear
    /// Auxiliary content that enhances or augments the primary content and can be accessed out of sequence.
    | NonLinear

/// Represents an XHTML content file in the EPUB.
type Xhtml = {
    Title: string
    FileName: string
    /// Indicates whether this file content contributes to the primary reading order and has to be read sequentially.
    /// Also, if the value is not `None` and the table of contents is to be autogenerated (`NavigationFile = Autogenerate`), this file will have an entry in the navigation document.
    /// See: https://www.w3.org/TR/epub-33/#sec-nav
    Navigation: Navigation option
    /// Optional SMIL file associated with this XHTML file for media overlays.
    /// If present, a corresponding `<item>` element for the SMIL file will be added to the manifest.
    /// See: https://www.w3.org/TR/epub-33/#sec-overlays-def
    Smil: SmilFile option
    /// Optional landmark type from the EPUB Structural Semantics Vocabulary, such as "titlepage", "glossary" or "appendix".
    /// If set and the navigation document is autogenerated, the file is listed in the landmarks under its `Title`.
    /// See: https://www.w3.org/TR/epub-33/#sec-nav-landmarks and https://www.w3.org/TR/epub-ssv-11/
    Landmark: string option
    Input: ContentInput }

/// Represents the manifest of files to be included in the EPUB.
type Manifest = {
    /// Optional cover image; stored as `cover` with its extension and marked with the `cover-image` property in the manifest.
    CoverImage: CoverImage option
    /// Navigation document, either autogenerated or provided as raw XHTML, saved as `_nav.xhtml`.
    NavigationFile: NavInput
    /// Title page added first to the spine before the navigation document.
    TitlePage: Xhtml
    /// XHTML content documents in reading order.
    ContentFiles: Xhtml seq
    /// Stylesheets referenced by generated XHTML documents.
    CssFiles: CssFile seq
    /// Additional resources (fonts, audio, etc.) to include in the package.
    OtherFiles: OtherFile seq
    /// Direction pages are turned in. `None` leaves it to the reading system.
    /// See: https://www.w3.org/TR/epub-33/#attrdef-spine-page-progression-direction
    PageProgressionDirection: PageProgressionDirection option }
